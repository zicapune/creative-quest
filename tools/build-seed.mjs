#!/usr/bin/env node
/* =====================================================================
   Builds the question seed from tools/questions.mjs into:
     supabase/schema.sql          (between @@SEED_START@@ / @@SEED_END@@)
     assets/js/demo-questions.js  (demo/preview mode only — never deployed live)
   Run:  node tools/build-seed.mjs
   ===================================================================== */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { QUESTIONS } from './questions.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const PATTERN = [1, 3, 0, 2, 2, 0, 3, 1]; // where the correct answer lands, cycling
const LET = 'ABCD';

const errors = [];
const ids = new Set();
const bySet = {};
const built = QUESTIONS.map((q) => {
  if (ids.has(q.id)) errors.push('Duplicate id ' + q.id);
  ids.add(q.id);
  if (!/^[AB]$/.test(q.set)) errors.push(q.id + ': set must be A or B');
  if (!Array.isArray(q.options) || q.options.length !== 4) errors.push(q.id + ': needs exactly 4 options');
  if (new Set(q.options.map((o) => o.toLowerCase())).size !== q.options.length) errors.push(q.id + ': duplicate options');
  bySet[q.set] = (bySet[q.set] || 0) + 1;
  const k = bySet[q.set] - 1;

  let options = q.options.slice();
  let correct = q.fixed ? q.correct : 0;
  if (!q.fixed) {
    const pos = PATTERN[k % PATTERN.length];
    const right = options.shift();
    options.splice(pos, 0, right);
    correct = pos;
  }
  if (!(correct >= 0 && correct < options.length)) errors.push(q.id + ': bad correct index');
  return { ...q, options, correct, sort: k + 1 };
});
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }

/* ---- SQL ---- */
const lit = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const rows = built.map((q) => '(' + [
  lit(q.id), q.sort, 'true', lit(q.category), lit(q.type), lit(q.topic), lit(q.q),
  ...q.options.map(lit), lit(LET[q.correct]), lit(q.why), lit(q.asset || ''), lit(q.alt || ''), lit(q.set)
].join(', ') + ')');
const sql = `insert into public.questions
  (id, sort, active, category, type, topic, question, option_a, option_b, option_c, option_d, correct, explanation, asset, asset_alt, set_name)
values
${rows.join(',\n')}
on conflict (id) do nothing;`;

const schemaPath = join(root, 'supabase/schema.sql');
const schema = readFileSync(schemaPath, 'utf8');
const a = schema.indexOf('-- @@SEED_START@@'), b = schema.indexOf('-- @@SEED_END@@');
if (a < 0 || b < 0) { console.error('Seed markers missing in schema.sql'); process.exit(1); }
writeFileSync(schemaPath, schema.slice(0, a) + '-- @@SEED_START@@ (generated by tools/build-seed.mjs — do not edit by hand)\n' + sql + '\n' + schema.slice(b));

/* ---- demo data ---- */
const demo = built.map((q) => ({ id: q.id, set: q.set, category: q.category, type: q.type, topic: q.topic, text: q.q,
  options: q.options, correct: q.correct, explanation: q.why, asset: q.asset || '', assetAlt: q.alt || '' }));
writeFileSync(join(root, 'assets/js/demo-questions.js'),
  '/* GENERATED by tools/build-seed.mjs — preview/demo mode only. The live deploy removes this file. */\n' +
  'window.CQ_DEMO_QUESTIONS = ' + JSON.stringify(demo) + ';\n');

const dist = {};
built.forEach((q) => { const key = q.set + LET[q.correct]; dist[key] = (dist[key] || 0) + 1; });
console.log('Questions:', bySet, '| correct-letter spread:', dist);
